/** Resolve a reagent by id, throwing early on typos in the rule table. */
export function getReagent(id: string): Reagent {
  const reagent = REAGENT_MAP[id]
  if (!reagent) throw new Error(`Unknown reagent id: ${id}`)
  return reagent
}

/** Non-throwing lookup for UI paths that render user-supplied data. */
export function findReagent(id: string): Reagent | undefined {
  return REAGENT_MAP[id]
}

